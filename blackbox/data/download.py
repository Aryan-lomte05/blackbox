"""Download the questions our agents work on (SYSTEM.md §3). Only questions:
every agent run is generated by us.

    py -3 -m blackbox.data.download                 # HotpotQA + GSM8K -> data/raw/
    py -3 -m blackbox.data.download --hotpot-n 3000
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from blackbox.core.store import DEFAULT_DIR

RAW_DIR = DEFAULT_DIR / "raw"
HOTPOT_FILE = "hotpotqa_distractor_validation.jsonl"
GSM8K_FILE = "gsm8k_main_test.jsonl"


def _write(path: Path, rows) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    n = 0
    with tmp.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    tmp.replace(path)
    return n


def download_hotpot(n: int | None = None, raw_dir: Path = RAW_DIR) -> int:
    from datasets import load_dataset

    ds = load_dataset("hotpotqa/hotpot_qa", "distractor", split="validation")
    if n is not None:
        ds = ds.select(range(min(n, len(ds))))
    rows = (
        {
            "id": r["id"], "question": r["question"], "answer": r["answer"], "type": r["type"], "level": r["level"],
            "supporting_titles": sorted(set(r["supporting_facts"]["title"])),
            "paragraphs": [
                {"title": t, "text": " ".join(s.strip() for s in sents)}
                for t, sents in zip(r["context"]["title"], r["context"]["sentences"])
            ],
        }
        for r in ds
    )
    return _write(raw_dir / HOTPOT_FILE, rows)


def download_gsm8k(n: int | None = None, raw_dir: Path = RAW_DIR) -> int:
    from datasets import load_dataset

    ds = load_dataset("openai/gsm8k", "main", split="test")
    if n is not None:
        ds = ds.select(range(min(n, len(ds))))
    rows = ({"id": i, "question": r["question"], "answer": r["answer"]} for i, r in enumerate(ds))
    return _write(raw_dir / GSM8K_FILE, rows)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Download HotpotQA and GSM8K questions into data/raw/")
    ap.add_argument("--hotpot-n", type=int, default=None, help="first N HotpotQA questions (default: all 7,405)")
    ap.add_argument("--gsm8k-n", type=int, default=None, help="first N GSM8K problems (default: all 1,319)")
    args = ap.parse_args()
    print(f"hotpotqa: {download_hotpot(args.hotpot_n)} questions -> {RAW_DIR / HOTPOT_FILE}")
    print(f"gsm8k:    {download_gsm8k(args.gsm8k_n)} problems -> {RAW_DIR / GSM8K_FILE}")
